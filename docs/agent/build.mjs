// Builds docs/AGENT_GUIDE.md, the single-file agent reference: docs/README.md
// followed by every docs/NN-*.md chapter in numeric order (00, 01, …, 99).
//
//   node docs/agent/build.mjs
//
// The result goes through the repo's own Prettier, so it passes CI's
// `npx prettier --check .` and rebuilding an unchanged tree leaves no diff.

import { spawnSync } from "node:child_process";
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";

const docsDir = path.dirname(import.meta.dirname);
const repoRoot = path.dirname(docsDir);
const outFile = "docs/AGENT_GUIDE.md";

// The prefixes are fixed-width, so sorting the names sorts them numerically.
const chapters = readdirSync(docsDir)
  .filter((name) => /^\d{2}-.+\.md$/.test(name))
  .sort();

const sections = ["README.md", ...chapters].map((name) => {
  const text = readFileSync(path.join(docsDir, name), "utf8").trimEnd();
  return `<!-- ===== ${name} ===== -->\n\n${text}\n\n---\n`;
});
writeFileSync(
  path.join(repoRoot, outFile),
  "<!-- GENERATED by docs/agent/build.mjs — edit docs/README.md and docs/NN-*.md instead. -->\n\n" +
    sections.join("\n"),
);

// `--no` stops npx from downloading some other Prettier when the repo's
// dependencies are not installed.
const prettier = spawnSync(
  "npx",
  ["--no", "--", "prettier", "--write", outFile],
  { cwd: repoRoot, encoding: "utf8", shell: process.platform === "win32" },
);
if (prettier.error) throw prettier.error;
if (prettier.status !== 0) {
  process.stderr.write(prettier.stdout + prettier.stderr);
  console.error(`Prettier failed on ${outFile}. Run \`npm run inst\` first?`);
  process.exit(1);
}

const numbers = chapters.map((name) => name.slice(0, 2)).join(" ");
console.log(`Wrote ${outFile}: README.md + chapters ${numbers}`);
